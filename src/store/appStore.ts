interface AppStoreState {
  apps: Record<AppId, AppDefinition>;
  dockAppIds: AppId[];
  pinAppToDock: (appId: AppId) => void;
  unpinAppFromDock: (appId: AppId) => void;
}

export const useAppStore = create<AppStoreState>((set) => ({
  apps: APP_REGISTRY,
  dockAppIds: [
    'ai',
    'terminal',
    'files',
    'editor',
    'browser',
    'calendar',
    'sysmon',
    'music',
    'arcade',
    'notes',
    'calc',
  ],
  pinAppToDock: (appId) =>
    set((state) => ({
      dockAppIds: state.dockAppIds.includes(appId) ? state.dockAppIds : [...state.dockAppIds, appId],
    })),
  unpinAppFromDock: (appId) =>
    set((state) => ({
      dockAppIds: state.dockAppIds.filter((id) => id !== appId),
    })),
}));
